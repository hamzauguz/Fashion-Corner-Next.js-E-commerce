const meta = {
  _createdAt: "2026-01-01T00:00:00Z",
  _updatedAt: "2026-01-01T00:00:00Z",
  _rev: "local",
};

type LocalImage = { _type: "image"; _key: string; url: string };
type Status = "new" | "hot" | "sale";

function img(url: string, key = "img-1"): LocalImage {
  return { _type: "image", _key: key, url };
}

/** Always-available local SVG image (no external CDN breakage). */
function photo(title: string, variant: string, slug: string, key = "img-1") {
  const params = new URLSearchParams({
    title,
    variant,
    label: variant,
    slug,
  });
  return img(`/api/product-image?${params.toString()}`, key);
}

function product(input: {
  id: string;
  name: string;
  slug: string;
  description: string;
  price: number;
  discount: number;
  stock: number;
  status: Status;
  variant: string;
  isFeatured: boolean;
  categoryIds: string[];
  brandId: string;
}) {
  return {
    _id: input.id,
    _type: "product" as const,
    ...meta,
    name: input.name,
    slug: { _type: "slug" as const, current: input.slug },
    description: input.description,
    price: input.price,
    discount: input.discount,
    stock: input.stock,
    status: input.status,
    variant: input.variant,
    isFeatured: input.isFeatured,
    categoryIds: input.categoryIds,
    brandId: input.brandId,
    images: [
      photo(input.name, input.variant, input.slug, "img-1"),
      photo(`${input.name} Alt`, input.variant, `${input.slug}-alt`, "img-2"),
    ],
  };
}

